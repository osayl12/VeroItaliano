const LangContext = createContext(null);

function initialLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'he' || saved === 'ar') return saved;
  } catch {}
  return 'he'; // default language: Hebrew
}

export function LangProvider({ children }) {
  const [lang, setLang] = useState(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = 'rtl';
    document.body.classList.toggle('lang-ar', lang === 'ar');
    try {
      localStorage.setItem('lang', lang);
    } catch {}
  }, [lang]);

  const t = (key) => dict[lang][key] ?? dict.he[key] ?? key;
  // pick the right language from a { he, ar } object, falling back to the other one
  const tr = (obj) => (obj ? obj[lang] || obj.he || obj.ar || '' : '');

  return <LangContext.Provider value={{ lang, setLang, t, tr }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
